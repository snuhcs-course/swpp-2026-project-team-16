package com.example.runtime.ui.route

import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import com.example.runtime.R
import com.example.runtime.data.remote.GeneratedRouteData
import com.example.runtime.data.remote.GeoJsonPoint
import com.example.runtime.data.remote.Place
import com.example.runtime.data.repository.RouteRepository
import com.example.runtime.ui.common.UiText
import com.example.runtime.ui.common.toUiText
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.Job
import kotlinx.coroutines.delay
import kotlinx.coroutines.launch
import java.util.Locale
import kotlin.math.roundToInt

class PlaceField {
    var input by mutableStateOf("")
        internal set
    var selected by mutableStateOf<Place?>(null)
        internal set
    var suggestions by mutableStateOf<List<Place>>(emptyList())
        internal set
    var isSearching by mutableStateOf(false)
        internal set
    var noResults by mutableStateOf(false)
        internal set
    var searchError by mutableStateOf<UiText?>(null)
        internal set
    internal var searchJob: Job? = null
}

enum class PickTarget { START, END }

class RouteViewModel(
    private val repository: RouteRepository = RouteRepository(),
) : ViewModel() {

    val startField = PlaceField()
    val endField = PlaceField()
    var distanceInput by mutableStateOf("")
    var pickTarget by mutableStateOf(PickTarget.START)

    var error by mutableStateOf<UiText?>(null)
        private set

    var generated by mutableStateOf<GeneratedRouteData?>(null)
        private set

    var saveState by mutableStateOf<SaveState>(SaveState.Idle)
        private set

    private var pendingStart: Place? = null
    private var pendingEnd: Place? = null
    private var pendingDistanceMeters: Int? = null
    private var pendingLanguage: String = DEFAULT_LANGUAGE
    private var searchLanguage: String = DEFAULT_LANGUAGE
    private var isGenerating = false

    fun onLanguageChange(language: String) {
        val normalized = normalizeLanguage(language)
        if (normalized == searchLanguage) return
        searchLanguage = normalized
        listOf(startField, endField)
            .filter { it.selected == null && it.input.trim().length >= MIN_QUERY_LENGTH }
            .forEach { search(it, it.input.trim()) }
    }

    fun onPlaceInputChange(field: PlaceField, text: String) {
        error = null
        field.input = text
        field.selected = null
        field.searchJob?.cancel()
        field.searchError = null
        field.noResults = false
        val query = text.trim()
        if (query.length < MIN_QUERY_LENGTH) {
            field.suggestions = emptyList()
            field.isSearching = false
            return
        }
        search(field, query)
    }

    private fun search(field: PlaceField, query: String) {
        field.searchJob?.cancel()
        val language = searchLanguage
        field.searchJob = viewModelScope.launch {
            delay(SEARCH_DEBOUNCE_MS)
            field.isSearching = true
            try {
                val places = repository.searchPlaces(query, language)
                field.suggestions = places
                field.noResults = places.isEmpty()
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                field.suggestions = emptyList()
                field.searchError = e.toUiText()
            } finally {
                field.isSearching = false
            }
        }
    }

    fun selectPlace(field: PlaceField, place: Place) {
        error = null
        field.searchJob?.cancel()
        field.selected = place
        field.input = place.name
        field.suggestions = emptyList()
        field.isSearching = false
        field.noResults = false
        field.searchError = null
    }

    fun selectPoint(field: PlaceField, name: String, longitude: Double, latitude: Double) {
        selectPlace(
            field,
            Place(
                name = name,
                address = "%.5f, %.5f".format(Locale.US, latitude, longitude),
                point = GeoJsonPoint.of(longitude, latitude),
            )
        )
    }

    fun showError(message: UiText) {
        error = message
    }

    fun prepare(language: String): Boolean {
        val start = startField.selected
        if (start == null) {
            error = UiText.Resource(R.string.error_start_point_required)
            return false
        }
        val end = endField.selected
        if (end == null && endField.input.isNotBlank()) {
            error = UiText.Resource(R.string.error_end_point_not_selected)
            return false
        }
        val meters = distanceInput.trim().toDoubleOrNull()
            ?.takeIf { it.isFinite() }
            ?.let { (it * 1000).roundToInt() }
        if (meters == null || meters <= MIN_DISTANCE_METERS) {
            error = UiText.Resource(R.string.error_distance_min)
            return false
        }
        error = null
        pendingStart = start
        pendingEnd = end
        pendingDistanceMeters = meters
        pendingLanguage = normalizeLanguage(language)
        return true
    }

    fun generate(onSuccess: () -> Unit, onFailure: () -> Unit) {
        val start = pendingStart ?: return onFailure()
        val distanceMeters = pendingDistanceMeters ?: return onFailure()
        if (isGenerating) return
        isGenerating = true
        viewModelScope.launch {
            try {
                generated = repository.generate(start, pendingEnd, distanceMeters, pendingLanguage)
                saveState = SaveState.Idle
                onSuccess()
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                error = e.toUiText()
                onFailure()
            } finally {
                isGenerating = false
            }
        }
    }

    fun save() {
        val route = generated ?: return
        if (saveState == SaveState.Saving || saveState == SaveState.Saved) return
        saveState = SaveState.Saving
        viewModelScope.launch {
            saveState = try {
                repository.saveTemporaryRoute(route.temporaryRouteId)
                SaveState.Saved
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                SaveState.Failed(e.toUiText())
            }
        }
    }

    private fun normalizeLanguage(language: String) =
        if (language in SUPPORTED_LANGUAGES) language else DEFAULT_LANGUAGE

    companion object {
        private const val MIN_DISTANCE_METERS = 100
        private const val MIN_QUERY_LENGTH = 2
        private const val SEARCH_DEBOUNCE_MS = 300L
        private const val DEFAULT_LANGUAGE = "en"
        private val SUPPORTED_LANGUAGES = setOf("en", "ko")
    }
}

sealed interface SaveState {
    data object Idle : SaveState
    data object Saving : SaveState
    data object Saved : SaveState
    data class Failed(val message: UiText) : SaveState
}
