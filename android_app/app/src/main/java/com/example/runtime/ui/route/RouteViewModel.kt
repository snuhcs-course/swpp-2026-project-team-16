    fun planNextFromDistance(distanceMeters: Int) {
        guidance = RunGuidance.ROUTE
        clearPlace(endField)
        distanceInput = String.format(Locale.US, "%.1f", (distanceMeters / 1000.0).coerceAtLeast(1.0)).removeSuffix(".0")
    }

    fun prepare(language: String): Boolean {
        val start = startField.selected
        if (start == null) {
            error = UiText.Resource(R.string.error_start_point_required)
            return false
        }

        val end = endField.selected
        if (end == null && endField.input.isNotBlank()) {
            error = UiText.Resource(R.string.error_end_point_not_selected)
            return false
        }

        val meters = distanceInput.trim()
            .toDoubleOrNull()
            ?.takeIf { it.isFinite() }
            ?.let { (it * 1000).roundToInt() }

        if (meters == null || meters <= MIN_DISTANCE_METERS) {
            error = UiText.Resource(R.string.error_distance_min)
            return false
        }

        if (paceMakerEnabled) {
            val selectedSegments = runPlan?.paceSegments.orEmpty()
            if (selectedSegments.any { it.endMeters > meters }) {
                error = UiText.Resource(R.string.goal_segment_exceeds_distance)
                return false
            }
            runPlan = (runPlan ?: RunPlan(
                runType = "easy",
                distanceMeters = meters,
                paceMinSeconds = paceMinSeconds,
                paceMaxSeconds = paceMaxSeconds,
            )).copy(
                distanceMeters = meters,
                paceMinSeconds = paceMinSeconds,
                paceMaxSeconds = paceMaxSeconds,
                routePreferences = RoutePreference.entries.filter { it in preferences }.map { it.apiValue },
                alertOnSlow = alertOnSlow,
                alertOnFast = alertOnFast,
            )
        } else {
            runPlan = null
        }

        error = null
        pendingStart = start
        pendingEnd = end
        pendingDistanceMeters = meters
        pendingLanguage = normalizeLanguage(language)
        return true
    }

    fun generate(onSuccess: () -> Unit, onFailure: () -> Unit) {
        val start = pendingStart ?: return onFailure()
        val distanceMeters = pendingDistanceMeters ?: return onFailure()

        if (isGenerating) return
        isGenerating = true
        val startedAt = Telemetry.startTime()
        Telemetry.track("route_generation", "started")

        sessionScope.launch {
            try {
                withTimeoutOrNull(NAME_LOOKUP_TIMEOUT_MS) {
                    listOfNotNull(startField.searchJob, endField.searchJob).joinAll()
                }
                val end = pendingEnd
                val namedStart = startField.selected?.takeIf { it.point == start.point } ?: start
                val namedEnd = end?.let { endField.selected?.takeIf { it.point == end.point } ?: end }
                val generatedData = repository.generate(
                    startingPoint = namedStart,
                    endPoint = namedEnd,
                    distanceMeters = distanceMeters,
                    language = pendingLanguage,
                    preferences = RoutePreference.entries.filter { it in preferences }.map { it.apiValue },
                    preferenceText = preferenceText.trim(),
                )
                Telemetry.track("route_generation", "succeeded", Telemetry.startTime() - startedAt)
                options = generatedData.options
                    .map { GeneratedRouteData(it.temporaryRouteId, it.route) }
                    .ifEmpty { listOf(generatedData) }
                selectedOption = 0
                generated = options.first()
                saveStates = emptyMap()
                savedRouteIds = emptyMap()
                shareState = ShareState.Idle
                sharedRouteIds = emptyMap()

                onSuccess()

                showElevationFor(options.first())
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                Telemetry.track("route_generation", "failed", Telemetry.startTime() - startedAt, Telemetry.failureCategory(e))
                Log.e("RouteViewModel", "Route generation failed", e)
                error = e.toUiText()
                onFailure()
            } finally {
                isGenerating = false
            }
        }
    }

    fun selectOption(index: Int) {
        val option = options.getOrNull(index) ?: return
        if (index == selectedOption) return
        selectedOption = index
        generated = option
        showElevationFor(option)
    }

    private fun showElevationFor(route: GeneratedRouteData) {
        elevationJob?.cancel()
        elevations = emptyList()
        slopes = emptyList()
        routeSlopeSegments = emptyList()
        uphillSections = emptyList()
        steepSectionSummary = ""
        elevationLoadState = ElevationLoadState.Loading
        val language = pendingLanguage
        elevationJob = sessionScope.launch { loadElevationData(route, language) }
    }

    private suspend fun loadElevationData(
        generatedData: GeneratedRouteData,
        language: String,
    ) {
        try {
            val coordinates = mutableListOf<Pair<Double, Double>>()

            generatedData.route.route.forEach { lineString ->
                lineString.coordinates.forEach { coordinate ->
                    if (coordinate.size >= 2) {
                        val longitude = coordinate[0]
                        val latitude = coordinate[1]

                        if (
                            latitude.isFinite() &&
                            longitude.isFinite() &&
                            latitude in -90.0..90.0 &&
                            longitude in -180.0..180.0
                        ) {
                            coordinates.add(latitude to longitude)
                        }
                    }
                }
            }

            if (coordinates.size < 2) {
                markElevationUnavailable(language)
                return
            }

            val sampledCoordinates =
                sampleCoordinatesAtIntervals(coordinates, SAMPLE_INTERVAL_METERS)

            val elevationResult = repository.getElevations(sampledCoordinates)

            if (elevationResult.isFailure) {
                markElevationUnavailable(language)
                return
            }

            val fetchedElevations = elevationResult.getOrThrow()

            if (fetchedElevations.size < 2) {
                markElevationUnavailable(language)
                return
            }

            elevations = fetchedElevations

            val segmentDistances = sampledCoordinates.zipWithNext { first, second ->
                distanceBetweenMeters(first, second)
            }

            val calculatedSlopes = repository.calculateSlopes(
                elevations = fetchedElevations,
                distancesMeters = segmentDistances,
            )

            slopes = calculatedSlopes
            uphillSections = findSteepSections(calculatedSlopes, segmentDistances)

            val routeGeometrySegments =
                splitRouteGeometryAtIntervals(coordinates, SAMPLE_INTERVAL_METERS)

            routeSlopeSegments =
                if (routeGeometrySegments.size == calculatedSlopes.size) {
                    routeGeometrySegments.zip(calculatedSlopes) { segmentCoordinates, slope ->
                        RouteSlopeSegment(
                            coordinates = segmentCoordinates.map { (latitude, longitude) ->
                                RouteCoordinate(
                                    latitude = latitude,
                                    longitude = longitude,
                                )
                            },
                            slopePercent = slope,
                        )
                    }
                } else {
                    // 구간 수 안 맞으면 기본 경로 색으로
                    emptyList()
                }
            steepSectionSummary = summarizeSteepSections(
                slopes = calculatedSlopes,
                segmentDistances = segmentDistances,
                language = language,
            )
            elevationLoadState = ElevationLoadState.Success
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.e("RouteViewModel", "Elevation processing failed", e)
            markElevationUnavailable(language)
        }
    }

    private fun markElevationUnavailable(language: String) {
        elevations = emptyList()
        slopes = emptyList()
        routeSlopeSegments = emptyList()
        uphillSections = emptyList()
        steepSectionSummary = noElevationMessage(language)
        elevationLoadState = ElevationLoadState.Error
    }

    /**
     5% 이상 오르막 경사구간 찾기
     250m 단위로, 경사 구간이 2개 이상 연속되면 상세 위치 요약
     */
    private fun findSteepSections(
        slopes: List<Double>,
        segmentDistances: List<Double>,
    ): List<RouteUphillSection> {
        val sections = mutableListOf<RouteUphillSection>()
        var totalDistance = 0.0
        var index = 0
        while (index < slopes.size) {
            if (slopes[index] >= STEEP_SLOPE_THRESHOLD) {
                val start = totalDistance
                var length = 0.0
                var count = 0
                while (index < slopes.size && slopes[index] >= STEEP_SLOPE_THRESHOLD) {
                    val segmentDistance = segmentDistances.getOrElse(index) { 0.0 }.coerceAtLeast(0.0)
                    length += segmentDistance
                    totalDistance += segmentDistance
                    count++
                    index++
                }
                if (count >= MIN_CONSECUTIVE_STEEP_SEGMENTS) {
                    sections += RouteUphillSection(start.roundToInt(), (start + length).roundToInt())
                }
            } else {
                totalDistance += segmentDistances.getOrElse(index) { 0.0 }.coerceAtLeast(0.0)
                index++
            }
        }
        return sections
    }

    private fun summarizeSteepSections(
        slopes: List<Double>,
        segmentDistances: List<Double>,
        language: String,
    ): String {
        if (slopes.isEmpty()) {
            return noElevationMessage(language)
        }

        val groups = mutableListOf<SteepGroup>()
        var totalDistance = 0.0
        var index = 0

        while (index < slopes.size) {
            if (slopes[index] >= STEEP_SLOPE_THRESHOLD) {
                val groupStartDistance = totalDistance
                var groupDuration = 0.0
                var groupSegmentCount = 0

                while (
                    index < slopes.size &&
                    slopes[index] >= STEEP_SLOPE_THRESHOLD
                ) {
                    val segmentDistance =
                        segmentDistances.getOrElse(index) { 0.0 }.coerceAtLeast(0.0)

                    groupDuration += segmentDistance
                    totalDistance += segmentDistance
                    groupSegmentCount++
                    index++
                }

                groups.add(
                    SteepGroup(
                        startMeters = groupStartDistance,
                        durationMeters = groupDuration,
                        segmentCount = groupSegmentCount,
                    ),
                )
            } else {
                totalDistance +=
                    segmentDistances.getOrElse(index) { 0.0 }.coerceAtLeast(0.0)
                index++
            }
        }

        if (groups.isEmpty()) {
            return if (language == KOREAN) {
                "평지 위주의 경로입니다."
            } else {
                "This route is mostly flat."
            }
        }

        val maximumSlope = slopes.maxOrNull() ?: 0.0
        val maximumSlopeText = "%.1f".format(Locale.US, maximumSlope)

        // 연속된 샘플 구간이 2개 이상인 구간만 상세 설명에 포함
        val detailedGroups = groups.filter {
            it.segmentCount >= MIN_CONSECUTIVE_STEEP_SEGMENTS
        }

        val details = detailedGroups.joinToString(separator = ", ") { group ->
            val startMeters = group.startMeters.roundToInt()
            val durationMeters = group.durationMeters.roundToInt()

            if (language == KOREAN) {
                "${startMeters}m 지점부터 ${durationMeters}m"
            } else {
                "from ${startMeters} m for ${durationMeters} m"
            }
        }

        val sectionCount = groups.size

        return if (language == KOREAN) {
            val base =
                "5% 이상의 급경사 구간이 ${sectionCount}개 있습니다. " +
                        "(최대 경사도: ${maximumSlopeText}%)"

            if (details.isNotBlank()) {
                "$base\n특히 $details 구간에서 급경사가 이어집니다."
            } else {
                base
            }
        } else {
            val sectionWord = if (sectionCount == 1) "section" else "sections"
            val base =
                "$sectionCount uphill $sectionWord reach 5% or more. " +
                        "(Maximum slope: ${maximumSlopeText}%)"

            if (details.isNotBlank()) {
                "$base\nIn particular, steep uphill sections continue $details."
            } else {
                base
            }
        }
    }

    private fun noElevationMessage(language: String): String =
        if (language == KOREAN) {
            "고도 정보를 불러오지 못했습니다."
        } else {
            "Elevation information is unavailable."
        }

    /**
     실제 경로 좌표를 따라 출발점, 250m 간격 지점, 도착점 반환
     마지막 구간은 실제 길이로 경사도 계산
     */
    private fun sampleCoordinatesAtIntervals(
        coordinates: List<Pair<Double, Double>>,
        intervalMeters: Double,
    ): List<Pair<Double, Double>> {
        if (coordinates.isEmpty()) return emptyList()

        // 연속으로 중복된 좌표 제거
        val cleanCoordinates = mutableListOf<Pair<Double, Double>>()
        coordinates.forEach { point ->
            if (
                cleanCoordinates.isEmpty() ||
                distanceBetweenMeters(cleanCoordinates.last(), point) > MIN_COORDINATE_DISTANCE_METERS
            ) {
                cleanCoordinates.add(point)
            }
        }

        if (cleanCoordinates.size <= 1) return cleanCoordinates

        val sampled = mutableListOf(cleanCoordinates.first())
        var distanceSinceLastSample = 0.0

        for (segmentIndex in 0 until cleanCoordinates.lastIndex) {
            val start = cleanCoordinates[segmentIndex]
            val end = cleanCoordinates[segmentIndex + 1]
            val segmentLength = distanceBetweenMeters(start, end)

            if (segmentLength <= 0.0) continue

            var distanceAlongSegment = 0.0

            while (
                distanceSinceLastSample +
                (segmentLength - distanceAlongSegment) >= intervalMeters
            ) {
                val distanceToNextSample =
                    intervalMeters - distanceSinceLastSample

                distanceAlongSegment += distanceToNextSample

                val fraction =
                    (distanceAlongSegment / segmentLength).coerceIn(0.0, 1.0)

                val sample = interpolateCoordinate(start, end, fraction)
                sampled.add(sample)
                distanceSinceLastSample = 0.0
            }

            distanceSinceLastSample += segmentLength - distanceAlongSegment
        }

        val routeEnd = cleanCoordinates.last()
        if (distanceBetweenMeters(sampled.last(), routeEnd) > MIN_COORDINATE_DISTANCE_METERS) {
            sampled.add(routeEnd)
        } else {
            // 마지막 샘플이 도착점과 거의 같으면 실제 도착 좌표로..
            sampled[sampled.lastIndex] = routeEnd
        }

        return sampled
    }





    fun save() {
        val route = generated ?: return
        if (saveState == SaveState.Saving || saveState == SaveState.Saved) return

        val id = route.temporaryRouteId
        saveStates = saveStates + (id to SaveState.Saving)
        sessionScope.launch {
            val result = try {
                repository.saveTemporaryRoute(id)?.let { savedRouteIds = savedRouteIds + (id to it) }
                SaveState.Saved
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                SaveState.Failed(e.toUiText())
            }
            saveStates = saveStates + (id to result)
        }
    }

    fun savedRouteId(temporaryRouteId: Int): Int? = savedRouteIds[temporaryRouteId]

    fun clearShareError() {
        if (shareState is ShareState.Failed) shareState = ShareState.Idle
    }

    fun share(title: String, description: String, onShared: (Int) -> Unit) {
        val route = generated ?: return
        val trimmedTitle = title.trim()
        if (trimmedTitle.isEmpty() || shareState == ShareState.Sharing || sharedRouteId != null) return

        val id = route.temporaryRouteId
        shareState = ShareState.Sharing
        sessionScope.launch {
            try {
                val savedId = savedRouteIds[id]
                val shared = if (savedId != null) {
                    communityRepository.shareRoute(savedId, trimmedTitle, description.trim())
                } else {
                    communityRepository.shareGeneratedRoute(id, trimmedTitle, description.trim())
                }
                sharedRouteIds = sharedRouteIds + (id to shared.id)
                shareState = ShareState.Idle
                onShared(shared.id)
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                shareState = ShareState.Failed(e.toUiText())
            }
        }
    }

    private fun normalizeLanguage(language: String): String =
        if (language in SUPPORTED_LANGUAGES) language else DEFAULT_LANGUAGE

    private data class SteepGroup(
        val startMeters: Double,
        val durationMeters: Double,
        val segmentCount: Int,
    )

    companion object {
        private const val MIN_DISTANCE_METERS = 100
        private const val MIN_QUERY_LENGTH = 2
        private const val SEARCH_DEBOUNCE_MS = 300L
        private const val NAME_LOOKUP_TIMEOUT_MS = 3_000L

        private const val SAMPLE_INTERVAL_METERS = 250.0
        private const val STEEP_SLOPE_THRESHOLD = 5.0
        private const val MIN_CONSECUTIVE_STEEP_SEGMENTS = 2

        private const val DEFAULT_LANGUAGE = "en"
        private const val KOREAN = "ko"
        private val SUPPORTED_LANGUAGES = setOf("en", "ko")
    }
}

