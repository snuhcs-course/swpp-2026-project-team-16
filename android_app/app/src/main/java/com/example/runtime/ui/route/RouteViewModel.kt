    fun togglePreference(preference: RoutePreference) {
        preferences = if (preference in preferences) {
            preferences - preference
        } else {
            preferences - setOfNotNull(CONFLICTING_PREFERENCES[preference]) + preference
        }
    }

    fun onPreferenceTextChange(text: String) {
        preferenceText = text.take(MAX_PREFERENCE_TEXT_LENGTH)
    }

    fun onGoalTextChange(text: String) {
        goalText = text.take(MAX_GOAL_TEXT_LENGTH)
        if (planState is PlanState.Failed) planState = PlanState.Idle
    }

    fun onPaceMakerEnabledChange(enabled: Boolean) {
        paceMakerEnabled = enabled
        if (!enabled) {
            alertOnSlow = false
            alertOnFast = false
            runPlan = null
            planState = PlanState.Idle
        } else {
            updatePlanSettings()
        }
    }

    fun updatePaceRange(range: ClosedFloatingPointRange<Float>) {
        val min = (range.start / 10f).roundToInt() * 10
        val max = (range.endInclusive / 10f).roundToInt() * 10
        paceMinSeconds = min.coerceIn(MIN_PACE_SECONDS, MAX_PACE_SECONDS - 10)
        paceMaxSeconds = max.coerceIn(paceMinSeconds + 10, MAX_PACE_SECONDS)
        updatePlanSettings()
    }

    fun onAlertOnSlowChange(enabled: Boolean) {
        alertOnSlow = enabled
        updatePlanSettings()
    }

    fun onAlertOnFastChange(enabled: Boolean) {
        alertOnFast = enabled
        updatePlanSettings()
    }

    fun paceAlertSettingsForFreeRun(): PaceAlertSettings? {
        if (!paceMakerEnabled || (!alertOnSlow && !alertOnFast)) return null
        return PaceAlertSettings(
            paceMinSeconds = paceMinSeconds,
            paceMaxSeconds = paceMaxSeconds,
            alertOnSlow = alertOnSlow,
            alertOnFast = alertOnFast,
        )
    }

    private fun updatePlanSettings() {
        runPlan = runPlan?.copy(
            paceMinSeconds = paceMinSeconds,
            paceMaxSeconds = paceMaxSeconds,
            alertOnSlow = alertOnSlow,
            alertOnFast = alertOnFast,
        )
    }

    fun requestPlan() {
        val text = goalText.trim()
        if (!paceMakerEnabled || text.isEmpty() || planState == PlanState.Loading) return
        val distanceMeters = distanceInput.trim().toDoubleOrNull()
            ?.takeIf { it.isFinite() && it > 0 }
            ?.let { (it * 1000).roundToInt() }
        planState = PlanState.Loading
        val startedAt = Telemetry.startTime()
        Telemetry.track("pace_plan", "started")
        sessionScope.launch {
            planState = try {
                val plan = coachRepository.planRun(
                        text = text,
                        distanceMeters = distanceMeters,
                        paceMinSeconds = paceMinSeconds,
                        paceMaxSeconds = paceMaxSeconds,
                        alertOnSlow = alertOnSlow,
                        alertOnFast = alertOnFast,
                    )
                applyPlan(plan)
                Telemetry.track("pace_plan", "succeeded", Telemetry.startTime() - startedAt)
                PlanState.Idle
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                Telemetry.track("pace_plan", "failed", Telemetry.startTime() - startedAt, Telemetry.failureCategory(e))
                PlanState.Failed(e.toUiText())
            }
        }
    }

    fun applyPlan(plan: RunPlan) {
        if (guidance == RunGuidance.FREE) guidance = RunGuidance.ROUTE
        paceMakerEnabled = true
        paceMinSeconds = plan.paceMinSeconds
        paceMaxSeconds = plan.paceMaxSeconds
        alertOnSlow = plan.alertOnSlow
        alertOnFast = plan.alertOnFast
        runPlan = plan
        distanceInput = formatKilometers(plan.distanceMeters)
        plan.routePreferences
            .mapNotNull { value -> RoutePreference.entries.firstOrNull { it.apiValue == value } }
            .filter { it !in preferences }
            .forEach(::togglePreference)
    }

    fun clearPlan() {
        runPlan = null
        planState = PlanState.Idle
    }

    fun updatePaceSegment(index: Int, segment: PaceSegment): Boolean {
        val plan = runPlan ?: return false
        if (
            segment.startMeters < 0 || segment.endMeters <= segment.startMeters
            || segment.endMeters > plan.distanceMeters
            || segment.paceMinSeconds !in MIN_PACE_SECONDS..MAX_PACE_SECONDS
            || segment.paceMaxSeconds !in segment.paceMinSeconds..MAX_PACE_SECONDS
        ) return false
        val segments = plan.paceSegments.toMutableList()
        if (index !in segments.indices) return false
        val previous = segments.getOrNull(index - 1)
        val next = segments.getOrNull(index + 1)
        if (previous != null && previous.endMeters > segment.startMeters) return false
        if (next != null && segment.endMeters > next.startMeters) return false
        segments[index] = segment
        runPlan = plan.copy(paceSegments = segments)
        return true
    }

    fun removePaceSegment(index: Int) {
        val plan = runPlan ?: return
        if (index !in plan.paceSegments.indices) return
        runPlan = plan.copy(paceSegments = plan.paceSegments.toMutableList().also { it.removeAt(index) })
    }

    fun addPaceSegment(): Boolean {
        val plan = runPlan ?: return false
        if (plan.paceSegments.size >= 12) return false
        val ordered = plan.paceSegments.sortedBy { it.startMeters }
        var start = 0
        for (segment in ordered) {
            if (segment.startMeters - start >= 200) break
            start = maxOf(start, segment.endMeters)
        }
        if (plan.distanceMeters - start < 200) return false
        val end = minOf(start + 1000, plan.distanceMeters)
        runPlan = plan.copy(
            paceSegments = (ordered + PaceSegment(start, end, paceMinSeconds, paceMaxSeconds))
                .sortedBy { it.startMeters },
        )
        return true
    }

    private fun formatKilometers(meters: Int): String {
        val km = meters / 1000.0
        return if (km % 1.0 == 0.0) km.toInt().toString() else String.format(Locale.US, "%.1f", km)
    }

    fun onLanguageChange(language: String) {
        val normalized = normalizeLanguage(language)
        if (normalized == searchLanguage) return

        searchLanguage = normalized
        listOf(startField, endField).forEach { field ->
            if (field.selected != null) {
                localize(field, normalized)
            } else if (field.input.trim().length >= MIN_QUERY_LENGTH) {
                search(field, field.input.trim())
            }
        }
    }

    private fun localize(field: PlaceField, language: String) {
        val place = field.selected ?: return
        val nameKo = place.nameKo ?: return
        val addressKo = place.addressKo.orEmpty()
        if (language == KOREAN) {
            showLocalized(field, place, nameKo, addressKo)
            return
        }

        field.searchJob?.cancel()
        field.searchJob = sessionScope.launch {
            field.isSearching = true
            try {
                val translated = repository.translatePlace(nameKo, addressKo, language)
                showLocalized(field, place, translated.name, translated.address)
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                Log.w("RouteViewModel", "Could not translate the selected place", e)
            } finally {
                field.isSearching = false
            }
        }
    }

    private fun showLocalized(field: PlaceField, place: Place, name: String, address: String) {
        if (field.selected != place) return
        val localized = place.copy(name = name, address = address)
        field.selected = localized
        field.input = name
        if (pendingStart == place) pendingStart = localized
        if (pendingEnd == place) pendingEnd = localized
    }

    private fun clearPlace(field: PlaceField) {
        field.searchJob?.cancel()
        field.input = ""
        field.selected = null
        field.suggestions = emptyList()
        field.isSearching = false
        field.noResults = false
        field.searchError = null
    }

    fun onPlaceInputChange(field: PlaceField, text: String) {
        error = null
        field.input = text
        field.selected = null
        field.searchJob?.cancel()
        field.searchError = null
        field.noResults = false

        val query = text.trim()
        if (query.length < MIN_QUERY_LENGTH) {
            field.suggestions = emptyList()
            field.isSearching = false
            return
        }

        search(field, query)
    }

    private fun search(field: PlaceField, query: String) {
        field.searchJob?.cancel()
        val language = searchLanguage

        field.searchJob = sessionScope.launch {
            delay(SEARCH_DEBOUNCE_MS)
            field.isSearching = true
            val startedAt = Telemetry.startTime()
            Telemetry.track("place_search", "started")

            try {
                val places = repository.searchPlaces(query, language)
                field.suggestions = places
                field.noResults = places.isEmpty()
                if (places.isEmpty()) {
                    Telemetry.track("place_search", "failed", Telemetry.startTime() - startedAt, "no_results")
                } else {
                    Telemetry.track("place_search", "succeeded", Telemetry.startTime() - startedAt)
                }
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                Telemetry.track("place_search", "failed", Telemetry.startTime() - startedAt, Telemetry.failureCategory(e))
                field.suggestions = emptyList()
                field.searchError = e.toUiText()
            } finally {
                field.isSearching = false
            }
        }
    }

    fun selectPlace(field: PlaceField, place: Place) {
        error = null
        field.searchJob?.cancel()
        field.selected = place
        field.input = place.name
        field.suggestions = emptyList()
        field.isSearching = false
        field.noResults = false
        field.searchError = null
    }

    fun selectPoint(
        field: PlaceField,
        name: String,
        longitude: Double,
        latitude: Double,
    ) {
        val point = GeoJsonPoint.of(longitude, latitude)
        selectPlace(
            field,
            Place(
                name = name,
                address = "%.5f, %.5f".format(Locale.US, latitude, longitude),
                point = point,
            ),
        )

        val language = searchLanguage
        field.searchJob = sessionScope.launch {
            field.isSearching = true
            try {
                val place = repository.reversePlace(latitude, longitude, language)
                if (place != null && field.selected?.point == point) {
                    field.selected = place.copy(point = point)
                    field.input = place.name
                }
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                Log.w("RouteViewModel", "Could not name the selected point", e)
            } finally {
                field.isSearching = false
            }
        }
    }

