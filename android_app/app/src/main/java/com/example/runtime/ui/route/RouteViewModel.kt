class PlaceField {
    var input by mutableStateOf("")
        internal set
    var selected by mutableStateOf<Place?>(null)
        internal set
    var suggestions by mutableStateOf<List<Place>>(emptyList())
        internal set
    var isSearching by mutableStateOf(false)
        internal set
    var noResults by mutableStateOf(false)
        internal set
    var searchError by mutableStateOf<UiText?>(null)
        internal set
    internal var searchJob: Job? = null
}

enum class PickTarget { START, END }

enum class RunGuidance(@StringRes val label: Int) {
    FREE(R.string.guidance_free),
    ROUTE(R.string.guidance_route),
}

enum class RoutePreference(val apiValue: String, @StringRes val label: Int) {
    FLAT("flat", R.string.preference_flat),
    HILLS("hills", R.string.preference_hills),
    FEW_SIGNALS("few_signals", R.string.preference_few_signals),
    EXACT_DISTANCE("exact_distance", R.string.preference_exact_distance),
}

private val CONFLICTING_PREFERENCES = mapOf(
    RoutePreference.FLAT to RoutePreference.HILLS,
    RoutePreference.HILLS to RoutePreference.FLAT,
)

const val MAX_PREFERENCE_TEXT_LENGTH = 200
enum class ElevationLoadState {
    Loading,
    Success,
    Error,
}

sealed interface PlanState {
    data object Idle : PlanState
    data object Loading : PlanState
    data class Failed(val message: UiText) : PlanState
}

const val MAX_GOAL_TEXT_LENGTH = 200
private const val DEFAULT_PACE_MIN_SECONDS = 330
private const val DEFAULT_PACE_MAX_SECONDS = 390
private const val MIN_PACE_SECONDS = 120
private const val MAX_PACE_SECONDS = 600

